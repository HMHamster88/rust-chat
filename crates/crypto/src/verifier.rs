//! Argon2id verifier persistence, byte-compatible with the Kotlin server's `config/verifier`.

use crate::{
    CryptoError, KdfParams, Result, ScramKeys, base64_decode, base64_encode, random_bytes,
};
use std::fmt::Write as _;
use std::path::Path;

pub const DEFAULT_MEMORY_KIB: u32 = 65_536;
pub const DEFAULT_ITERATIONS: u32 = 3;
pub const DEFAULT_PARALLELISM: u32 = 1;
const FILE_VERSION: &str = "1";

#[derive(Debug, Clone)]
pub struct PasswordVerifier {
    pub kdf: KdfParams,
    pub stored_key: [u8; 32],
    pub server_key: [u8; 32],
}

impl PasswordVerifier {
    pub fn create(
        password: &str,
        memory_kib: u32,
        iterations: u32,
        parallelism: u32,
    ) -> Result<Self> {
        if password.is_empty() {
            return Err(CryptoError::EmptyPassword);
        }
        let kdf = KdfParams {
            alg: "argon2id".into(),
            salt: base64_encode(&random_bytes(16)),
            m: memory_kib,
            t: iterations,
            p: parallelism,
        };
        let auth_key = crate::scram::derive_auth_key(password, &kdf)?;
        let ScramKeys {
            stored_key,
            server_key,
            ..
        } = crate::scram::keys(&auth_key);
        Ok(Self {
            kdf,
            stored_key,
            server_key,
        })
    }

    pub fn with_defaults(password: &str) -> Result<Self> {
        Self::create(
            password,
            DEFAULT_MEMORY_KIB,
            DEFAULT_ITERATIONS,
            DEFAULT_PARALLELISM,
        )
    }

    pub fn salt(&self) -> Result<Vec<u8>> {
        base64_decode(&self.kdf.salt)
    }
}

pub fn load_verifier(path: &Path) -> Result<PasswordVerifier> {
    let text = std::fs::read_to_string(path)?;
    parse_verifier(&text)
}

pub fn save_verifier(path: &Path, verifier: &PasswordVerifier) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, format_verifier(verifier))?;
    restrict_to_owner(path);
    Ok(())
}

pub fn format_verifier(verifier: &PasswordVerifier) -> String {
    let mut out = String::new();
    out.push_str("# rust-chat password verifier\n");
    out.push_str("# Generated by `rust-chat-server init`. Keep this file private.\n");
    let _ = writeln!(out, "version={FILE_VERSION}");
    let _ = writeln!(out, "alg=argon2id");
    let _ = writeln!(out, "salt={}", verifier.kdf.salt);
    let _ = writeln!(out, "m={}", verifier.kdf.m);
    let _ = writeln!(out, "t={}", verifier.kdf.t);
    let _ = writeln!(out, "p={}", verifier.kdf.p);
    let _ = writeln!(out, "storedKey={}", base64_encode(&verifier.stored_key));
    let _ = writeln!(out, "serverKey={}", base64_encode(&verifier.server_key));
    out
}

pub fn parse_verifier(text: &str) -> Result<PasswordVerifier> {
    use std::collections::HashMap;
    let mut values = HashMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            values.insert(key.trim(), value.trim());
        }
    }

    let get = |key: &str| -> Result<String> {
        values
            .get(key)
            .map(|value| (*value).to_owned())
            .ok_or_else(|| CryptoError::MalformedVerifier(format!("missing `{key}`")))
    };
    let get_u32 = |key: &str| -> Result<u32> {
        get(key)?
            .parse()
            .map_err(|_| CryptoError::MalformedVerifier(format!("`{key}` is not a number")))
    };

    if get("version")? != FILE_VERSION {
        return Err(CryptoError::MalformedVerifier(format!(
            "unsupported version {}",
            get("version")?
        )));
    }
    if get("alg")? != "argon2id" {
        return Err(CryptoError::MalformedVerifier(format!(
            "unsupported KDF {}",
            get("alg")?
        )));
    }

    let stored_key = fixed32(&base64_decode(&get("storedKey")?)?)?;
    let server_key = fixed32(&base64_decode(&get("serverKey")?)?)?;
    Ok(PasswordVerifier {
        kdf: KdfParams {
            alg: "argon2id".into(),
            salt: get("salt")?,
            m: get_u32("m")?,
            t: get_u32("t")?,
            p: get_u32("p")?,
        },
        stored_key,
        server_key,
    })
}

fn fixed32(bytes: &[u8]) -> Result<[u8; 32]> {
    bytes
        .try_into()
        .map_err(|_| CryptoError::MalformedVerifier("storedKey/serverKey must be 32 bytes".into()))
}

fn restrict_to_owner(path: &Path) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600));
    }
    #[cfg(not(unix))]
    {
        let _ = path;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fast_verifier(password: &str) -> PasswordVerifier {
        PasswordVerifier::create(password, 8, 1, 1).unwrap()
    }

    #[test]
    fn file_round_trip_preserves_the_verifier() {
        let verifier = fast_verifier("hunter2");
        let text = format_verifier(&verifier);
        let parsed = parse_verifier(&text).unwrap();
        assert_eq!(parsed.kdf.salt, verifier.kdf.salt);
        assert_eq!(parsed.kdf.m, 8);
        assert_eq!(parsed.stored_key, verifier.stored_key);
        assert_eq!(parsed.server_key, verifier.server_key);
    }

    #[test]
    fn kotlin_format_is_accepted() {
        let text = "\
# kotlin-chat password verifier
version=1
alg=argon2id
salt=AAAAAAAAAAAAAAAAAAAAAA==
m=65536
t=3
p=1
storedKey=AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=
serverKey=AQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQE=
";
        let parsed = parse_verifier(text).unwrap();
        assert_eq!(parsed.kdf.m, 65_536);
        assert_eq!(parsed.stored_key, [0u8; 32]);
    }

    #[test]
    fn malformed_inputs_are_explained() {
        assert!(parse_verifier("version=2\nalg=argon2id\n").is_err());
        assert!(parse_verifier("version=1\nalg=bcrypt\n").is_err());
        assert!(parse_verifier("").is_err());
    }

    #[test]
    fn saving_and_loading_a_file_works() {
        let dir = std::env::temp_dir().join(format!(
            "rust-chat-verifier-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let path = dir.join("verifier");
        let verifier = fast_verifier("secret");
        save_verifier(&path, &verifier).unwrap();
        let loaded = load_verifier(&path).unwrap();
        assert_eq!(loaded.stored_key, verifier.stored_key);
        let _ = std::fs::remove_dir_all(dir);
    }
}
